export function getEventTaxonomyForSpecies(pathway: SpeciesPathway): TaxonomyEventItem[] {
  return SENIOR_EVENT_TAXONOMY.filter(
    (item) => item.speciesSupport === 'both' || item.speciesSupport === pathway
  );
}

export function getTopLevelEventsForSpecies(pathway: SpeciesPathway): TaxonomyEventItem[] {
  const list = getEventTaxonomyForSpecies(pathway);
  if (pathway === 'cat') {
    return list.filter((item) => item.isTopLevelCat);
  }
  return list.filter((item) => item.isTopLevelDog);
}
